/**
 * Jacquard — browser demo.
 *
 * The picture woven on a jacquard loom. The one idea, from `source/Jacquard.h`:
 * at every crossing of a cloth one thread is on top, the warp running down or
 * the weft running across, and a jacquard head can lift every warp end on its
 * own — but colour comes from threads (one warp colour, one weft colour a pick
 * from the shuttles loaded), no float may run past Max Float, and tone is
 * carried by weave structure. So the encoder is an optimiser under
 * constraints, solved exactly pick by pick down the cloth.
 *
 * Like teletext, this plugin is **not only a shader**, and the two halves of
 * the page are not equally faithful:
 *
 *   The shaders are the plugin's. `VERTEX_BODY`, `CELLS_BODY` and `RENDER_BODY`
 *   below are `kVertexBody`, `kCellsBody` and `kRenderBody` from
 *   `source/Shaders.cpp`, spliced in by `demo/tools/sync_shaders.py` with their
 *   tabs and comments, and assembled with the same `#version 410 core` line
 *   `shaders::assemble` prepends. `demo/tools/check_shaders.py` compares them
 *   character for character and `tools/verify.sh` runs it.
 *
 *   The CPU half is a PORT, in `loom.js` — Controls.cpp, Palette.cpp (the
 *   k-means), Weave.cpp, Encoder.cpp (the exact row programme) and Loom.cpp —
 *   and the frame sequence below is `Jacquard::ProcessOpenGL`'s. Nothing checks
 *   a port but a reader; jqtest checks the C++ and has never heard of this page.
 *
 * ------------------------------------------------------ the readback
 *
 * The plugin reads the Ends x Picks crossing means back with `glGetTexImage(
 * …, GL_FLOAT )` every frame, runs the palette and the loom on the CPU, and
 * uploads an Ends x Picks RG8 lift texture. The page does exactly that: one
 * `readPixels` of an RGBA32F target as FLOAT (EXT_color_buffer_float), the
 * loom in JavaScript, and an RG8 upload. It stalls the pipeline where the
 * plugin's does.
 *
 * ------------------------------------------------------- what is missing
 *
 * **Nothing audio**: Jacquard has no audio path. **No clock**: the plugin reads
 * no time, so the page's clock only moves the clip. **The About block is
 * absent**, as on every page in this suite. **The four integer controls are
 * dropdowns**: the kit has no integer control, so Ends, Picks, Max Float and
 * Shuttles are dropdowns of every value in the plugin's range, as teletext's
 * and copperlist's are. The Perturb and forced-structure test hooks are at
 * rest (0 and -1), as the shipped plugin has them.
 */


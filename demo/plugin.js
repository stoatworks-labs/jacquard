/// shaders::assemble: the version line, then the body.
const assemble = (body) => VERSION + body;

//===========================================================================
// The renderer: Jacquard::ProcessOpenGL, in its order.
//
//   1. cells      Ends x Picks, RGBA32F: each crossing's mean in linear light
//   2. read-back  readPixels as FLOAT
//   3. shuttles   the k-means of the crossings (Clip) or a swatch card
//   4. the loom   pick by pick, top to bottom; an Ends x Picks RG8 upload
//   5. render     the cloth as lit thread, onto the canvas
//===========================================================================

/// The k-means reads at most this many crossings a frame (Jacquard.cpp).
const K_PALETTE_SAMPLES = 16384;

/// What the line under the canvas reports. Filled by the renderer.
const telemetry = { ends: 0, picks: 0, shuttles: 0, programmes: 0, remembered: false, cpuMillis: 0, colours: [] };

/// Driven checks only (see AGENTS.md, "The browser demo"): `fresh()` puts the
/// renderer back to a new instance's state; `afterRender`, if set, is called
/// inside the frame with the GL context, so a script can read the canvas
/// before it is presented; `lastMeans` is the frame's read-back and
/// `lastCloth` what the ported loom wove from it.
const hooks = { afterRender: null, fresh: null, lastMeans: null, lastInput: null, lastCloth: null, lastShuttles: null };

function createRenderer(gl, quad) {
  const cellsShader = new Program(gl, assemble(VERTEX_BODY), assemble(CELLS_BODY), 'cells');
  const renderShader = new Program(gl, assemble(VERTEX_BODY), assemble(RENDER_BODY), 'render');
  const cells = new PassBuffer(gl, { filter: 'nearest' });

  // Ends x Picks RG8: R 255 where the warp is on top, G the pick's shuttle.
  const liftTexture = gl.createTexture();
  let liftEnds = 0;
  let liftPicks = 0;

  // The state across frames: the shuttles' k-means, the palette it was run
  // for, and the last cloth, which the next frame remembers.
  let kmeans = new L.KMeans();
  let lastPaletteSource = -1;
  let cloth = null;
  let means = new Float32Array(0);
  let liftBytes = new Uint8Array(0);

  hooks.fresh = () => {
    kmeans = new L.KMeans();
    lastPaletteSource = -1;
    cloth = null;
  };

  return {
    render({ input, params, width: vpW, height: vpH }) {
      // The host stores every parameter as a float.
      const p = (id) => Math.fround(params.get(id));
      const width = input.width;
      const height = input.height;
      hooks.lastInput = input;

      //------------------------------------------------------------------
      // What the controls say.
      //------------------------------------------------------------------
      const ends = L.ends(integerValue('ends', p('ends')));
      const aspect = L.threadAspect(p('threadAspect'));
      const picks = L.picks(integerValue('picks', p('picks')), ends, width, height, aspect);
      const maxFloat = L.maxFloat(integerValue('maxFloat', p('maxFloat')));
      const shuttleCount = L.shuttles(integerValue('shuttles', p('shuttles')));
      const source = L.optionIndex(p('palette'), L.SOURCE_COUNT);
      const mode = L.optionIndex(p('structure'), L.MODE_COUNT);
      const shading = Math.min(Math.max(p('shading'), 0), 1);
      const zoom = Math.fround(L.zoom(p('zoom')));
      const mixAmount = Math.min(Math.max(p('mix'), 0), 1);
      const warp = [L.toLinear(p('warpR')), L.toLinear(p('warpG')), L.toLinear(p('warpB'))];

      //------------------------------------------------------------------
      // Buffers.
      //------------------------------------------------------------------
      cells.ensure(ends, picks, gl.RGBA32F);
      if (ends !== liftEnds || picks !== liftPicks) {
        gl.bindTexture(gl.TEXTURE_2D, liftTexture);
        gl.pixelStorei(gl.UNPACK_ALIGNMENT, 1);
        gl.texImage2D(gl.TEXTURE_2D, 0, gl.RG8, ends, picks, 0, gl.RG, gl.UNSIGNED_BYTE, null);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.NEAREST);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.NEAREST);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.CLAMP_TO_EDGE);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.CLAMP_TO_EDGE);
        gl.bindTexture(gl.TEXTURE_2D, null);
        liftEnds = ends;
        liftPicks = picks;
      }

      //------------------------------------------------------------------
      // 1. Cells: one linear mean per crossing.
      //------------------------------------------------------------------
      cells.bind();
      gl.disable(gl.BLEND);
      cellsShader.use();
      bindTexture(gl, 0, input.texture);
      cellsShader.setSampler('InputTexture', 0);
      gl.uniform2i(cellsShader.location('InputSize'), width, height);
      gl.uniform2i(cellsShader.location('Grid'), ends, picks);
      quad.draw();

      // Read them back: at most 320 x 320 x 4 floats. The one stall, and the
      // price of an encoder that is exact.
      if (means.length !== ends * picks * 4) means = new Float32Array(ends * picks * 4);
      gl.pixelStorei(gl.PACK_ALIGNMENT, 1);
      gl.readPixels(0, 0, ends, picks, gl.RGBA, gl.FLOAT, means);
      hooks.lastMeans = means;

      //------------------------------------------------------------------
      // 2. The shuttles, and the loom. CPU — here, the JavaScript port.
      //------------------------------------------------------------------
      const started = performance.now();
      if (source !== lastPaletteSource) kmeans.reset();
      lastPaletteSource = source;

      let shuttles;
      if (source === L.K_CLIP) {
        const count = ends * picks;
        kmeans.update(means, count, shuttleCount, Math.floor((count + K_PALETTE_SAMPLES - 1) / K_PALETTE_SAMPLES));
        shuttles = kmeans.centres.map((c) => c.slice());
      } else {
        shuttles = L.fixed(source, shuttleCount);
      }

      cloth = L.weave(means, { ends, picks, warp, shuttles, maxFloat, mode }, cloth);
      hooks.lastCloth = cloth;
      hooks.lastShuttles = shuttles;

      // uploadLift
      if (liftBytes.length !== ends * picks * 2) liftBytes = new Uint8Array(ends * picks * 2);
      for (let j = 0; j < picks; j += 1) {
        for (let i = 0; i < ends; i += 1) {
          const cell = j * ends + i;
          liftBytes[cell * 2] = cloth.lift[cell] ? 255 : 0;
          liftBytes[cell * 2 + 1] = cloth.weft[j];
        }
      }
      gl.bindTexture(gl.TEXTURE_2D, liftTexture);
      gl.pixelStorei(gl.UNPACK_ALIGNMENT, 1);
      gl.texSubImage2D(gl.TEXTURE_2D, 0, 0, 0, ends, picks, gl.RG, gl.UNSIGNED_BYTE, liftBytes);
      gl.bindTexture(gl.TEXTURE_2D, null);

      telemetry.cpuMillis = performance.now() - started;
      telemetry.ends = ends;
      telemetry.picks = picks;
      telemetry.shuttles = shuttles.length;
      telemetry.programmes = cloth.programmes;
      telemetry.remembered = cloth.remembered;
      telemetry.colours = shuttles.map((c) => c.map(L.toEncoded));

      //------------------------------------------------------------------
      // 3. Render, onto the canvas. The host's viewport is the whole canvas.
      //------------------------------------------------------------------
      gl.bindFramebuffer(gl.FRAMEBUFFER, null);
      gl.viewport(0, 0, vpW, vpH);

      renderShader.use();
      bindTexture(gl, 0, liftTexture);
      bindTexture(gl, 1, input.texture);
      renderShader.setSampler('Lift', 0);
      renderShader.setSampler('Source', 1);
      renderShader.set('MaxUV', 1.0, 1.0);
      gl.uniform2i(renderShader.location('OutSize'), width, height);
      gl.uniform2i(renderShader.location('Grid'), ends, picks);
      renderShader.set('Warp', warp[0], warp[1], warp[2]);
      const packedShuttles = new Float32Array(L.MAX_SHUTTLES * 3);
      for (let k = 0; k < shuttles.length && k < L.MAX_SHUTTLES; k += 1) {
        packedShuttles[k * 3] = shuttles[k][0];
        packedShuttles[k * 3 + 1] = shuttles[k][1];
        packedShuttles[k * 3 + 2] = shuttles[k][2];
      }
      renderShader.setArray('Shuttle', packedShuttles, 3);
      renderShader.setInt('Shuttles', shuttles.length);
      renderShader.set('Zoom', zoom);
      renderShader.set('Shading', shading);
      renderShader.set('MixAmount', mixAmount);
      renderShader.setInt('Perturb', 0);
      quad.draw();

      if (hooks.afterRender) hooks.afterRender(gl, input);

      // Unbind so nothing reads a framebuffer's own texture next frame.
      bindTexture(gl, 1, null);
      bindTexture(gl, 0, null);
    },
  };
}


/// std::lround: halves away from zero (Math.round rounds -2.5 to -2).
function lround(x) {
  return x < 0 ? -Math.floor(-x + 0.5) : Math.floor(x + 0.5);
}

const clampInt = (v, lo, hi) => (v < lo ? lo : v > hi ? hi : v);

export function optionIndex(value, count) {
  return clampInt(lround(value), 0, count - 1);
}

export function ends(value) {
  return clampInt(lround(value), CONTROLS_H.kEndsMin, CONTROLS_H.kEndsMax);
}

export function picks(value, endCount, width, height, aspect) {
  const explicitPicks = lround(value);
  if (explicitPicks > 0) return Math.min(explicitPicks, CONTROLS_H.kPicksMax);
  if (width <= 0 || height <= 0) return 1;
  // An end is width / ends pixels wide; a pick aspect times that tall. Double.
  const p = (height * endCount) / (width * aspect);
  return clampInt(lround(p), 1, CONTROLS_H.kPicksMax);
}

export function threadAspect(value) {
  return 0.5 * Math.pow(4.0, clampInt(value, 0.0, 1.0));
}

export function maxFloat(value) {
  return clampInt(lround(value), CONTROLS_H.kMaxFloatMin, CONTROLS_H.kMaxFloatMax);
}

export function shuttles(value) {
  return clampInt(lround(value), CONTROLS_H.kShuttlesMin, CONTROLS_H.kShuttlesMax);
}

export function zoom(value) {
  return Math.pow(8.0, clampInt(value, 0.0, 1.0));
}


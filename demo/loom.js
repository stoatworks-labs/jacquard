const F_HALF = f32(0.5);
const F_QUARTER = f32(0.25);

/// Loom.cpp's `Encoding`: the sRGB encoding by table, 4096 intervals on
/// [0, 1], linearly interpolated.
const ENC_SIZE = 4096;
const ENC_TABLE = new Float32Array(ENC_SIZE + 1);
for (let k = 0; k <= ENC_SIZE; k += 1) ENC_TABLE[k] = toEncoded(f32(k / ENC_SIZE));

function enc(v) {
  v = f32(clampF(v, 0, 1) * ENC_SIZE);
  const k = Math.min(Math.trunc(v), ENC_SIZE - 1);
  const f = f32(v - k);
  return f32(ENC_TABLE[k] + f32(f32(ENC_TABLE[k + 1] - ENC_TABLE[k]) * f));
}

/// A squared error (never negative) to cost units, rounded half up, through
/// a float as the C++ does it.
function quantise(squaredError) {
  return Math.trunc(f32(f32(squaredError * K_COST_SCALE) + F_HALF));
}


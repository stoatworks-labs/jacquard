const MODE_PLAIN = 1;
const MODE_TWILL = 2;
const MODE_SATIN = 3;
export const MODE_COUNT = MODE_NAMES.length;

/// Warp over `over` of a `repeat`, for the twills; zeros for anything else.
function twillShape(structure) {
  switch (structure) {
    case S.twill31: return [3, 4];
    case S.twill21: return [2, 3];
    case S.twill22: return [2, 4];
    case S.twill12: return [1, 3];
    case S.twill13: return [1, 4];
    default: return [0, 0];
  }
}

function repeatOf(structure) {
  switch (structure) {
    case S.warpSolid:
    case S.weftSolid: return 1;
    case S.warpSatin:
    case S.weftSatin: return 5;
    case S.plain: return 2;
    default: return twillShape(structure)[1];
  }
}

/// Weft coverage as num / den, in double (Weave.cpp's `double Coverage`).
function coverage(structure) {
  switch (structure) {
    case S.warpSolid: return 0 / 1;
    case S.weftSolid: return 1 / 1;
    case S.warpSatin: return 1 / 5;
    case S.weftSatin: return 4 / 5;
    case S.plain: return 1 / 2;
    default: {
      const [over, repeat] = twillShape(structure);
      return (repeat - over) / repeat;
    }
  }
}

function family(mode) {
  switch (mode) {
    case MODE_PLAIN: return [S.plain];
    case MODE_TWILL: return [S.twill31, S.twill22, S.twill13];
    case MODE_SATIN: return [S.warpSatin, S.weftSatin];
    default:
      // Auto: the solids at the ends, the satins next, the three- and
      // four-end twills in the midtones; plain and 3/1, 1/3 left out.
      return [S.warpSolid, S.warpSatin, S.twill21, S.twill22, S.twill12, S.weftSatin, S.weftSolid];
  }
}

/// Warp on top at end i, pick j (both absolute, non-negative). No Perturb.
function warpUp(structure, i, j) {
  switch (structure) {
    case S.warpSolid: return true;
    case S.weftSolid: return false;
    case S.warpSatin: return (i + 2 * j) % 5 !== 0;
    case S.weftSatin: return (i + 2 * j) % 5 === 0;
    case S.plain: return (i + j) % 2 === 0;
    default: {
      const [over, repeat] = twillShape(structure);
      return (i + j) % repeat < over;
    }
  }
}

function gcd(a, b) {
  while (b) [a, b] = [b, a % b];
  return a;
}

function latticeStep(period) {
  for (let s = 2; s <= period - 2; s += 1) if (gcd(s, period) === 1) return s;
  return 1;
}


// Encoder.cpp: the exact row programme.
//
// Costs are integers held in a Float64Array; kInfinite is Infinity, which
// compares the same way INT64_MAX / 4 does and is never added to.
//===========================================================================

const INF = Infinity;

class RowTable {
  resize(crossings, colours, limit) {
    this.n = crossings;
    this.colours = colours;
    this.maxFloat = limit;
    if (!this.cost || this.cost.length !== colours * crossings * 2) this.cost = new Float64Array(colours * crossings * 2);
    else this.cost.fill(0);
    if (!this.forbidden || this.forbidden.length !== crossings) this.forbidden = new Int8Array(crossings);
    this.forbidden.fill(-1);
  }
}

function runCap(table) {
  return table.maxFloat > 0 ? Math.min(table.maxFloat, table.n) : Math.max(table.n, 1);
}

let dpCur = new Float64Array(0);
let dpNxt = new Float64Array(0);
let dpFrom = new Uint16Array(0);

/// The programme for one colour: state (value, run 1..M) at v * M + r - 1.
/// Returns the cost and fills x.
function programme(table, c, x) {
  const n = table.n;
  const M = runCap(table);
  const cost = table.cost;
  const forbidden = table.forbidden;
  if (dpCur.length < 2 * M) {
    dpCur = new Float64Array(2 * M);
    dpNxt = new Float64Array(2 * M);
  }
  if (dpFrom.length < n * 2) dpFrom = new Uint16Array(n * 2);
  let cur = dpCur;
  let nxt = dpNxt;
  cur.fill(INF, 0, 2 * M);
  nxt.fill(INF, 0, 2 * M);
  dpFrom.fill(0, 0, n * 2);
  const from = dpFrom;
  const base = c * n * 2;

  for (let v = 0; v < 2; v += 1) if (forbidden[0] !== v) cur[v * M] = cost[base + v];

  for (let i = 1; i < n; i += 1) {
    // The cheapest run of each value ending at i - 1, and its length.
    let best0 = INF;
    let best1 = INF;
    let bestR0 = 0;
    let bestR1 = 0;
    for (let r = 0; r < M; r += 1) {
      const value = cur[r];
      if (value < best0) {
        best0 = value;
        bestR0 = r + 1;
      }
    }
    for (let r = 0; r < M; r += 1) {
      const value = cur[M + r];
      if (value < best1) {
        best1 = value;
        bestR1 = r + 1;
      }
    }

    nxt.fill(INF, 0, 2 * M);
    for (let u = 0; u < 2; u += 1) {
      if (forbidden[i] === u) continue;
      const here = cost[base + i * 2 + u];
      const other = u === 0 ? best1 : best0;
      // Start a run of u after a run of the other value.
      if (other < INF) {
        nxt[u * M] = other + here;
        from[i * 2 + u] = u === 0 ? bestR1 : bestR0;
      }
      // Extend a run of u that is still shorter than M.
      for (let r = 1; r < M; r += 1) {
        const previous = cur[u * M + r - 1];
        if (previous < INF) nxt[u * M + r] = previous + here;
      }
    }
    const t = cur;
    cur = nxt;
    nxt = t;
  }

  let total = INF;
  let endV = 0;
  let endR = 0;
  for (let v = 0; v < 2; v += 1) {
    for (let r = 0; r < M; r += 1) {
      if (cur[v * M + r] < total) {
        total = cur[v * M + r];
        endV = v;
        endR = r + 1;
      }
    }
  }
  if (total >= INF) return INF;

  // Walk back run by run.
  x.fill(0, 0, n);
  let i = n - 1;
  let v = endV;
  let r = endR;
  while (i >= 0) {
    const start = i - r + 1;
    for (let k = start; k <= i; k += 1) x[k] = v;
    if (start === 0) break;
    const previousR = from[start * 2 + v];
    i = start - 1;
    v = 1 - v;
    r = previousR;
  }
  return total;
}

/// SolveRow, the exact half: colours tried in order of a lower bound, stopping
/// when the bound reaches the best row found. The greedy weaver (the
/// harness's negative control) is not ported.
function solveRow(table, result) {
  result.colour = 0;
  result.cost = INF;
  result.feasible = false;
  result.programmesRun = 0;
  const n = table.n;
  const K = table.colours;
  if (n <= 0 || K <= 0) return result;
  if (!result.x || result.x.length !== n) result.x = new Uint8Array(n);
  if (!result.scratch || result.scratch.length !== n) result.scratch = new Uint8Array(n);

  const bound = new Float64Array(K);
  for (let c = 0; c < K; c += 1) {
    let sum = 0;
    for (let i = 0; i < n; i += 1) {
      let cheapest = INF;
      for (let v = 0; v < 2; v += 1) {
        if (table.forbidden[i] !== v) cheapest = Math.min(cheapest, table.cost[(c * n + i) * 2 + v]);
      }
      sum += cheapest;
    }
    bound[c] = sum;
  }
  const order = [];
  for (let c = 0; c < K; c += 1) order.push(c);
  order.sort((a, b) => (bound[a] < bound[b] ? -1 : bound[b] < bound[a] ? 1 : 0)); // stable

  const x = result.scratch;
  for (const c of order) {
    if (bound[c] >= result.cost) break; // no remaining colour can beat the row found
    const cost = programme(table, c, x);
    result.programmesRun += 1;
    if (cost < result.cost) {
      result.colour = c;
      result.x.set(x);
      result.cost = cost;
      result.feasible = true;
    }
  }
  return result;
}


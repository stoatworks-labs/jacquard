/**
 * loom::Weave. `means` is ends x picks linear RGBA floats (stride 4), row 0 the
 * top pick. `s` is { ends, picks, warp: [r,g,b] linear, shuttles: [[r,g,b]...],
 * maxFloat, mode }. `previous` is last frame's cloth, remembered when it is
 * the same grid, shuttle count and mode. Returns a new cloth.
 */
export function weave(means, s, previous = null) {
  const n = s.ends;
  const K = clampInt(s.shuttles.length, 1, MAX_SHUTTLES);
  const M = s.maxFloat <= 0 ? 0 : s.maxFloat;
  const forcedStructure = -1;

  const out = emptyCloth();
  out.ends = n;
  out.picks = s.picks;
  out.lift = new Uint8Array(n * s.picks);
  out.weft = new Uint8Array(s.picks);
  out.structure = new Uint8Array(n * s.picks);
  out.shuttleCount = K;
  out.mode = s.mode;
  out.forcedStructure = forcedStructure;
  if (n <= 0 || s.picks <= 0 || !s.shuttles) return out;

  const remember = previous !== null && previous !== out && previous.ends === n && previous.picks === s.picks
    && previous.shuttleCount === K && previous.mode === s.mode && previous.forcedStructure === forcedStructure
    && previous.lift.length === out.lift.length;
  out.remembered = remember;

  //-----------------------------------------------------------------
  // Per frame: the family, and every (structure, shuttle) mixture in
  // linear light, encoded.
  //-----------------------------------------------------------------
  const fam = family(s.mode);
  const levels = fam.length;

  const W = s.warp;
  const mixEncoded = new Float32Array(levels * K * 3);
  for (let l = 0; l < levels; l += 1) {
    const f = f32(coverage(fam[l]));
    const g = f32(1 - f);
    for (let c = 0; c < K; c += 1) {
      const weft = s.shuttles[c];
      const at = (l * K + c) * 3;
      for (let ch = 0; ch < 3; ch += 1) {
        const m = f32(f32(f * weft[ch]) + f32(g * W[ch]));
        mixEncoded[at + ch] = toEncoded(m);
      }
    }
  }

  const warpEncoded = [toEncoded(W[0]), toEncoded(W[1]), toEncoded(W[2])];
  const weftEncoded = [];
  for (let c = 0; c < K; c += 1) weftEncoded.push([toEncoded(s.shuttles[c][0]), toEncoded(s.shuttles[c][1]), toEncoded(s.shuttles[c][2])]);

  // The range the threads span, per channel, on the encoding.
  const lo = warpEncoded.slice();
  const hi = warpEncoded.slice();
  for (const w of weftEncoded) {
    for (let ch = 0; ch < 3; ch += 1) {
      lo[ch] = Math.min(lo[ch], w[ch]);
      hi[ch] = Math.max(hi[ch], w[ch]);
    }
  }

  //-----------------------------------------------------------------
  // The picks, top to bottom.
  //-----------------------------------------------------------------
  const table = new RowTable();
  table.resize(n, K, M);
  const chosen = new Uint8Array(K * n);
  const carry = new Float32Array(n * 3);
  const residual = new Float32Array(n * 3);
  const targetEncoded = new Float32Array(n * 3);
  const lattice = new Uint8Array(n);
  const pattern = new Uint8Array(levels * n);
  const repeat = new Int32Array(levels);
  const tiles = new Uint8Array(levels * MAX_REPEAT * MAX_REPEAT);
  for (let l = 0; l < levels; l += 1) {
    const R = repeatOf(fam[l]);
    repeat[l] = R;
    for (let jj = 0; jj < R; jj += 1) {
      for (let ii = 0; ii < R; ii += 1) tiles[(l * MAX_REPEAT + jj) * MAX_REPEAT + ii] = warpUp(fam[l], ii, jj) ? 1 : 0;
    }
  }
  // The mixtures again, as three eight-lane arrays a shuttle, padded far away.
  const lanes = new Float32Array(K * 3 * LANES).fill(1.0e6);
  for (let c = 0; c < K; c += 1) {
    for (let l = 0; l < levels; l += 1) {
      const at = (l * K + c) * 3;
      lanes[(c * 3 + 0) * LANES + l] = mixEncoded[at];
      lanes[(c * 3 + 1) * LANES + l] = mixEncoded[at + 1];
      lanes[(c * 3 + 2) * LANES + l] = mixEncoded[at + 2];
    }
  }
  const step = M > 0 ? latticeStep(M + 1) : 1;
  const columnValue = new Uint8Array(n);
  const columnRun = new Int32Array(n);
  const distance = new Float32Array(LANES);
  const row = {};

  for (let j = 0; j < s.picks; j += 1) {
    for (let i = 0; i < n; i += 1) {
      const t = (j * n + i) * 4;
      for (let ch = 0; ch < 3; ch += 1) {
        targetEncoded[i * 3 + ch] = f32(enc(means[t + ch]) + f32(K_CARRY * carry[i * 3 + ch]));
      }
    }
    // The tie lattice along this pick: ( i + s j ) mod ( M + 1 ) == 0.
    for (let i = 0; i < n; i += 1) lattice[i] = M > 0 && (i + step * j) % (M + 1) === 0 ? 1 : 0;

    // Each structure's pattern along this pick, from its tiled repeat.
    for (let l = 0; l < levels; l += 1) {
      const R = repeat[l];
      const line = (l * MAX_REPEAT + (j % R)) * MAX_REPEAT;
      for (let i = 0, ii = 0; i < n; i += 1, ii = ii + 1 === R ? 0 : ii + 1) pattern[l * n + i] = tiles[line + ii];
    }

    for (let c = 0; c < K; c += 1) {
      const laneR = (c * 3 + 0) * LANES;
      const laneG = (c * 3 + 1) * LANES;
      const laneB = (c * 3 + 2) * LANES;
      const weftE = weftEncoded[c];
      const shuttleHold = remember && previous.weft[j] !== c ? K_HOLD_SHUTTLE : 0;
      for (let i = 0; i < n; i += 1) {
        // Tone to structure: the mixture nearest the target, on the
        // encoding. Ties go to the lower coverage.
        const ter = targetEncoded[i * 3];
        const teg = targetEncoded[i * 3 + 1];
        const teb = targetEncoded[i * 3 + 2];
        for (let l = 0; l < LANES; l += 1) {
          const dr = f32(ter - lanes[laneR + l]);
          const dg = f32(teg - lanes[laneG + l]);
          const db = f32(teb - lanes[laneB + l]);
          distance[l] = f32(f32(f32(dr * dr) + f32(dg * dg)) + f32(db * db));
        }
        let best = 0;
        let bestD = distance[0];
        for (let l = 1; l < levels; l += 1) {
          if (distance[l] < bestD) {
            bestD = distance[l];
            best = l;
          }
        }
        const cell = j * n + i;
        let E = quantise(bestD);
        if (remember && fam[best] !== previous.structure[cell]) {
          // Keep last frame's structure while it is nearly as good.
          for (let l = 0; l < levels; l += 1) {
            if (fam[l] === previous.structure[cell]) {
              const kept = quantise(distance[l]);
              if (kept <= E + K_HOLD_STRUCTURE) {
                best = l;
                E = kept;
              }
            }
          }
        }
        const d = pattern[best * n + i];
        const shown = d === 1 ? weftE : warpEncoded;
        const er = f32(ter - shown[0]);
        const eg = f32(teg - shown[1]);
        const eb = f32(teb - shown[2]);
        const tie = K_TIE + quantise(f32(f32(f32(er * er) + f32(eg * eg)) + f32(eb * eb))) - (lattice[i] ? K_LATTICE : 0);
        const at = (c * n + i) * 2;
        table.cost[at + d] = E + shuttleHold;
        table.cost[at + 1 - d] = E + tie + shuttleHold;
        if (remember) table.cost[at + 1 - previous.lift[cell]] += K_HOLD_LIFT;
        chosen[c * n + i] = best;
      }
    }

    for (let i = 0; i < n; i += 1) table.forbidden[i] = M > 0 && columnRun[i] >= M ? columnValue[i] : -1;

    solveRow(table, row);
    out.cost += row.cost;
    out.programmes += row.programmesRun;
    if (!row.feasible) out.infeasiblePicks += 1;

    const c = row.colour;
    out.weft[j] = c;
    for (let i = 0; i < n; i += 1) {
      // `row.x.empty() ? 0 : row.x[ i ]`: x is only written by a feasible row.
      const x = row.feasible ? row.x[i] : 0;
      const cell = j * n + i;
      const level = chosen[c * n + i];
      out.lift[cell] = x;
      out.structure[cell] = fam[level];

      if (columnRun[i] > 0 && columnValue[i] === x) columnRun[i] += 1;
      else {
        columnValue[i] = x;
        columnRun[i] = 1;
      }

      // What the crossing still owes, on the encoding: the target clamped to
      // the threads' own range, per channel, less the mixture, bounded.
      const at = (level * K + c) * 3;
      for (let ch = 0; ch < 3; ch += 1) {
        const te = targetEncoded[i * 3 + ch];
        residual[i * 3 + ch] = clampF(f32(clampF(te, lo[ch], hi[ch]) - mixEncoded[at + ch]), -K_CARRY_LIMIT, K_CARRY_LIMIT);
      }
    }

    // Spread 1/4, 1/2, 1/4 to the next pick, renormalised at the selvedges.
    for (let i = 0; i < n; i += 1) {
      let w = F_HALF;
      let r = f32(F_HALF * residual[i * 3]);
      let g = f32(F_HALF * residual[i * 3 + 1]);
      let b = f32(F_HALF * residual[i * 3 + 2]);
      for (const side of [i - 1, i + 1]) {
        if (side >= 0 && side < n) {
          w = f32(w + F_QUARTER);
          r = f32(r + f32(F_QUARTER * residual[side * 3]));
          g = f32(g + f32(F_QUARTER * residual[side * 3 + 1]));
          b = f32(b + f32(F_QUARTER * residual[side * 3 + 2]));
        }
      }
      carry[i * 3] = f32(r / w);
      carry[i * 3 + 1] = f32(g / w);
      carry[i * 3 + 2] = f32(b / w);
    }
  }
  return out;
}

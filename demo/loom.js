// The float literals, as the float the C++ compiler makes of each.
const F_0_04045 = f32(0.04045);
const F_12_92 = f32(12.92);
const F_0_055 = f32(0.055);
const F_1_055 = f32(1.055);
const F_2_4 = f32(2.4);
const F_0_0031308 = f32(0.0031308);
const F_INV_2_4 = f32(1 / F_2_4); // 1.0f / 2.4f, folded in float
const F_LUMA_R = f32(0.2126);
const F_LUMA_G = f32(0.7152);
const F_LUMA_B = f32(0.0722);

/// std::clamp on floats: v < lo ? lo : hi < v ? hi : v.
const clampF = (v, lo, hi) => (v < lo ? lo : hi < v ? hi : v);

export function toLinear(v) {
  v = clampF(v, 0, 1);
  return v <= F_0_04045 ? f32(v / F_12_92) : f32(Math.pow(f32(f32(v + F_0_055) / F_1_055), F_2_4));
}

export function toEncoded(v) {
  v = clampF(v, 0, 1);
  return v <= F_0_0031308 ? f32(F_12_92 * v) : f32(f32(F_1_055 * f32(Math.pow(v, F_INV_2_4))) - F_0_055);
}

/// Linear colours are [r, g, b] triples of floats.
function fromSwatch(s) {
  return [toLinear(f32(s[0])), toLinear(f32(s[1])), toLinear(f32(s[2]))];
}

function distance2(a, b) {
  const dr = f32(a[0] - b[0]);
  const dg = f32(a[1] - b[1]);
  const db = f32(a[2] - b[2]);
  return f32(f32(f32(dr * dr) + f32(dg * dg)) + f32(db * db));
}

function luma(c) {
  return f32(f32(f32(F_LUMA_R * c[0]) + f32(F_LUMA_G * c[1])) + f32(F_LUMA_B * c[2]));
}

/// A fixed swatch set's first K colours, in linear light.
export function fixed(source, count) {
  count = clampInt(count, 1, MAX_SHUTTLES);
  const out = [];
  for (let k = 0; k < count; k += 1) {
    if (source === K_MONO) {
      // Evenly spaced greys in the encoding, black to white.
      const v = count > 1 ? f32(k / (count - 1)) : 0.5;
      const l = toLinear(v);
      out.push([l, l, l]);
    } else if (source === K_BRIGHT) {
      out.push(fromSwatch(BRIGHT_SWATCHES[k]));
    } else {
      out.push(fromSwatch(HERITAGE_SWATCHES[k]));
    }
  }
  return out;
}

/// KMeans::Update. Lloyd's algorithm in linear light, warm-started from the
/// last frame's centres when K is unchanged; a cold start seeds by farthest
/// point from the median by luminance.
export class KMeans {
  constructor() {
    this.centres = [];
    this.coldStarts = 0;
  }

  reset() {
    this.centres = [];
  }

  update(rgba, count, k, sampleStep) {
    k = clampInt(k, 1, MAX_SHUTTLES);
    sampleStep = Math.max(1, sampleStep);

    const points = [];
    for (let i = 0; i < count; i += sampleStep) {
      const t = i * 4;
      points.push([rgba[t], rgba[t + 1], rgba[t + 2]]);
    }
    if (points.length === 0) {
      this.centres = [];
      for (let c = 0; c < k; c += 1) this.centres.push([f32(0.2), f32(0.2), f32(0.2)]);
      return;
    }

    let iterations = 3;
    if (this.centres.length !== k) {
      this.coldStarts += 1;
      iterations = 6;
      const lumas = points.map(luma);
      const byLuma = points.map((_, i) => i);
      // std::stable_sort by luminance; Array.prototype.sort is stable.
      byLuma.sort((a, b) => (lumas[a] < lumas[b] ? -1 : lumas[b] < lumas[a] ? 1 : 0));
      this.centres = [points[byLuma[Math.floor(byLuma.length / 2)]].slice()];
      const nearest = new Float32Array(points.length);
      for (let i = 0; i < points.length; i += 1) nearest[i] = distance2(points[i], this.centres[0]);
      while (this.centres.length < k) {
        let farthest = 0;
        for (let i = 1; i < points.length; i += 1) if (nearest[i] > nearest[farthest]) farthest = i;
        this.centres.push(points[farthest].slice());
        const back = this.centres[this.centres.length - 1];
        for (let i = 0; i < points.length; i += 1) nearest[i] = Math.min(nearest[i], distance2(points[i], back));
      }
    }

    const centres = this.centres;
    const sum = new Float64Array(k * 3);
    const members = new Int32Array(k);
    for (let iteration = 0; iteration < iterations; iteration += 1) {
      sum.fill(0);
      members.fill(0);
      let worst = f32(-1);
      let worstI = 0;
      for (let i = 0; i < points.length; i += 1) {
        let best = 0;
        let bestD = distance2(points[i], centres[0]);
        for (let c = 1; c < k; c += 1) {
          const d = distance2(points[i], centres[c]);
          if (d < bestD) {
            bestD = d;
            best = c;
          }
        }
        if (bestD > worst) {
          worst = bestD;
          worstI = i;
        }
        // Summed in double, as the C++ does.
        sum[best * 3] += points[i][0];
        sum[best * 3 + 1] += points[i][1];
        sum[best * 3 + 2] += points[i][2];
        members[best] += 1;
      }
      for (let c = 0; c < k; c += 1) {
        const m = members[c];
        if (m === 0) {
          // An empty shuttle takes the worst-served colour in the frame.
          centres[c] = points[worstI].slice();
          continue;
        }
        centres[c] = [f32(sum[c * 3] / m), f32(sum[c * 3 + 1] / m), f32(sum[c * 3 + 2] / m)];
      }
    }
  }
}

